#!/usr/bin/env python3
"""Convert Sigma rules to Splunk SPL.

Every ``*.yml`` under ``detections/sigma/`` is converted with pySigma's Splunk
backend plus the processing pipelines in ``scripts/pipelines/``. Output is
written to the mirrored path under ``detections/splunk/`` with a ``.spl``
extension.

Usage:
    python scripts/convert.py           # (re)generate SPL
    python scripts/convert.py --check   # exit 1 if committed SPL is stale
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from sigma.backends.splunk import SplunkBackend
from sigma.collection import SigmaCollection
from sigma.processing.pipeline import ProcessingPipeline

REPO_ROOT = Path(__file__).resolve().parent.parent
SIGMA_DIR = REPO_ROOT / "detections" / "sigma"
SPLUNK_DIR = REPO_ROOT / "detections" / "splunk"
PIPELINE_DIR = Path(__file__).resolve().parent / "pipelines"


def load_pipeline() -> ProcessingPipeline:
    """Merge all YAML pipelines in scripts/pipelines/ (ordered by priority)."""
    pipelines = [
        ProcessingPipeline.from_yaml(p.read_text(encoding="utf-8"))
        for p in sorted(PIPELINE_DIR.glob("*.yml"))
    ]
    return sum(pipelines, ProcessingPipeline())


def convert_rule(rule_path: Path, pipeline: ProcessingPipeline | None = None) -> str:
    """Return the rendered .spl file content for one Sigma rule file."""
    collection = SigmaCollection.from_yaml(rule_path.read_text(encoding="utf-8"))
    backend = SplunkBackend(processing_pipeline=pipeline or load_pipeline())
    queries = backend.convert(collection)
    rel = rule_path.relative_to(REPO_ROOT).as_posix()

    blocks = []
    for rule, query in zip(collection.rules, queries):
        header = "\n".join(
            [
                "``` AUTO-GENERATED by scripts/convert.py - do not edit by hand. ```",
                f"``` Source: {rel} ```",
                f"``` Title:  {rule.title} ```",
                f"``` ID:     {rule.id} | Level: {rule.level} ```",
            ]
        )
        blocks.append(f"{header}\n{query}\n")
    return "\n".join(blocks)


def output_path(rule_path: Path) -> Path:
    return (SPLUNK_DIR / rule_path.relative_to(SIGMA_DIR)).with_suffix(".spl")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="do not write; fail if any committed .spl differs from a fresh conversion",
    )
    args = parser.parse_args(argv)

    pipeline = load_pipeline()
    rules = sorted(SIGMA_DIR.rglob("*.yml"))
    if not rules:
        print(f"No Sigma rules found under {SIGMA_DIR}", file=sys.stderr)
        return 1

    stale = []
    for rule_path in rules:
        out = output_path(rule_path)
        rendered = convert_rule(rule_path, pipeline)
        rel_out = out.relative_to(REPO_ROOT)
        if args.check:
            current = out.read_text(encoding="utf-8") if out.exists() else None
            status = "ok" if current == rendered else "STALE"
            if current != rendered:
                stale.append(rel_out)
            print(f"[{status}] {rel_out}")
        else:
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_text(rendered, encoding="utf-8")
            print(f"[wrote] {rel_out}")

    if stale:
        print(
            f"\n{len(stale)} SPL file(s) out of date. Run `make convert` and commit the result.",
            file=sys.stderr,
        )
        return 1
    print(f"\n{len(rules)} rule(s) converted.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
